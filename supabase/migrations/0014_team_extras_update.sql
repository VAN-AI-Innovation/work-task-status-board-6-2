-- ---------------------------------------------------------------------------
-- 0014 — 팀 전용 칸(`tasks.extras`)을 화면에서 고칠 수 있게 연다
-- ---------------------------------------------------------------------------
--
-- `0013` 5절은 `extras`를 일부러 닫았다. 근거는 「열면 이 표가 시트 편집기가 된다」였다.
-- 뒤집는 이유는 팀 전용 컬럼(`콘텐츠 유형`·`섭외 상태`·`문의 유형` …)이 **전부 그 안에
-- 있기 때문이다** — 공통 13칸만 열어 두면 촬영팀 사람이 자기 업무의 절반을 화면에서 못
-- 고치고, 그 절반을 고치려면 시트를 열어 다시 업로드해야 한다. 그것은 이 제품의 약속과
-- 어긋난다.
--
-- 여는 것은 `extras` 하나뿐이다. **`raw`·`source_*`는 그대로 닫혀 있다** — 그쪽은 시트
-- 원본과 감사 기록이고, 화면에는 그것을 고칠 이유가 없다.
--
-- ⚠ **민감 키 차단은 앱 층에만 있다.** `isSensitiveExtraKey`(연락처·계정·이메일·전화)가
--   `PATCH /api/tasks/[id]`의 문 앞에서 막지만, 이 GRANT는 열쇠를 가진 사람이 PostgREST로
--   직접 쓰는 길까지 막지는 못한다. 행 범위는 `tasks_update_scope`가 그대로 지고 있어
--   자기 범위 밖 업무는 여전히 못 건드린다.

grant update (extras) on public.tasks to authenticated;

-- 만들 때도 같은 칸이 필요하다. 넣지 않으면 웹에서 만든 촬영팀 업무가 팀 전용 칸이 통째로
-- 빈 채로 서고, 사람이 곧바로 수정 폼을 다시 열어 채워야 한다.
grant insert (extras) on public.tasks to authenticated;
