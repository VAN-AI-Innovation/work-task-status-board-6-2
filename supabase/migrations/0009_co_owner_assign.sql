-- `0008`이 `owner_member_id`·`owner_name_raw`를 열었다. 거기에 한 칸을 더한다.
-- **정책은 또 손대지 않는다** — `tasks_update_scope`가 이미 「누가 어느 행을」을 정해 뒀고
-- (`0003` 3-4), 이 칸은 그 판정에 쓰이지 않으므로 `with check`가 달라질 것이 없다.
--
--   admin  → 아무 행이나
--   lead   → 자기 팀 행
--   member → 자기 행. 다만 앱이 `canAssignOwner`로 먼저 막는다
--
-- ⚠ **공동 담당은 이름 배열이지 계정이 아니다.** 그래서 공동 담당으로 지정된 사람은
--   `member`로 로그인해도 **그 업무를 자기 화면에서 보지 못한다** — 부원의 열람 조건은
--   `owner_member_id = my_member_id()` 하나뿐이기 때문이다 (`0003` 3-4 · `viewer-scope.ts`).
--   시트의 「공동 담당」 칸이 원래 이름 목록이라 지금까지도 그랬고, 이 변경이 그 성질을
--   바꾸지는 않는다. 공동 담당자도 자기 화면에서 보게 하려면 `co_owner_member_ids uuid[]`
--   컬럼과 **정책 두 개의 member 갈래**를 함께 고쳐야 한다 — 그것은 별개의 결정이다.
--
-- ⚠ 다음 시트 업로드가 이 칸을 덮어쓴다. `owner_member_id`가 이미 지고 있는 성질과 같다
--   (`ADR-001` — 시트가 진실의 원천이다).
